/**
 * Builds the static playground into playground/dist (deployed to GitHub Pages).
 *   npm run playground:build
 */

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { build } from 'esbuild';
import { HARNESS_POLICY, loadScenarios } from '../src/harness.js';

const out = join('playground', 'dist');
mkdirSync(out, { recursive: true });

const scenarios = loadScenarios().map((s) => ({
  id: s.id,
  kind: s.kind,
  category: s.category,
  description: s.description,
  request: s.request,
}));
const policyYaml = readFileSync(HARNESS_POLICY, 'utf8').replace(/^# yaml-language-server:.*\n/, '');
writeFileSync(
  join('playground', 'data.gen.ts'),
  `// Generated by playground/build.ts. Do not edit.\nexport const SCENARIOS = ${JSON.stringify(scenarios)} as const;\nexport const POLICY_YAML = ${JSON.stringify(policyYaml)};\n`,
);

await build({
  entryPoints: ['playground/app.ts'],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  sourcemap: false,
  outfile: join(out, 'app.js'),
  logLevel: 'warning',
});
copyFileSync(join('playground', 'index.html'), join(out, 'index.html'));
copyFileSync(join('docs', 'social-preview.png'), join(out, 'og.png'));
console.log(`playground built: ${out} (${scenarios.length} scenarios)`);
